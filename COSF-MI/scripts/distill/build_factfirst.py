"""
Fine-tune set ft_v2 from ft_v1: the same prompts and the same train/val split, with fact-first replies.

Why: the 104M fine-tune on ft_v1 copied the persona's "vivid comparison" template without the knowledge to fill it
(experiments/results/ft_l100/notes.md). common.PERSONA asks for comparisons; this persona asks for the plain answer first.

Per category:
  explain, chat, oasst2  regenerated by the teacher with PERSONA_V2: correct plain answer first, at most one comparison
                         after it, and a kind, plain reply with no jokes for sad or serious topics. The follow-up-question
                         coin (common.ASK_RATE) is redrawn per request. --n candidates per request; the first that passes
                         the filters is kept, otherwise the request is dropped.
  gsm8k                  regenerated with MATH_SYSTEM (no persona): steps as plain equations, no playful lines,
                         'Answer: N' last and equal to the GSM8K gold (data/distill_pilot/src_gsm8k.jsonl).
  arith                  rebuilt without the teacher from meta (op|a|b): "a op b = gold" then "Answer: gold".
  story                  copied unchanged (0.4% simile openers in ft_v1).

Filters on regenerated replies, in order: truncated, identity, format, latex, code, answer_leak / wrong_answer /
answer_not_last, too_long (common.AuraLength, as ft_v1), simile_first (a comparison in the first sentence),
too_many_similes (more than one), playful_math (gsm8k: any comparison, joke marker or '!'), playful_serious (a prompt
the teacher judges SERIOUS gets a reply with a comparison, a joke marker or '!'), then exact/near duplicates
(common.NearDup, per category).

Output: data/distill_pilot/ft_v2/{train,val}.jsonl, rejected.jsonl, run_config.json, report.md, review.md (random kept
replies per category). --limit N rebuilds only the first N rows per category of each split (smoke test, --out elsewhere).

Usage (from COSF-MI/; vLLM venv, WSL has no nvcc):
  VLLM_USE_FLASHINFER_SAMPLER=0 ~/venvs/vllm/bin/python -I scripts/distill/build_factfirst.py --out data/distill_pilot/ft_v2
"""
import argparse
import json
import random
import re
import subprocess
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

SRC = C.ROOT / "data/distill_pilot/ft_v1"
GSM8K_SRC = C.ROOT / "data/distill_pilot/src_gsm8k.jsonl"

PERSONA_V2 = ("You are Aura, a small, friendly AI who lives on a home computer and is still learning. Aura is warm and "
              "curious. Follow these rules. "
              "1. Start with the correct, plain answer: the first sentence states the actual fact, or replies directly, in "
              "everyday words. Never start with a comparison, 'imagine', 'picture' or 'it's like'. "
              "2. Being correct matters most. If you are not sure of a fact, leave it out. "
              "3. After the facts you may add at most one short comparison, and only if it really helps; often none is "
              "better. "
              "4. Match the user's mood. If the topic is sad, worrying or serious (illness, injury, death, loss, fear, "
              "bullying, a bad day), give a kind, calm, plain answer: no jokes, no comparisons, no exclamation marks. "
              "5. Use short sentences and everyday words. If you need a special word, explain it simply. "
              "Write plain text only: no LaTeX, no code, no markdown headings. "
              "You can't see a clock, the internet or the news, so never make up times, dates or current events. "
              "Never say who made you, and never mention any company, model or product name.")
SYSTEM_V2 = {
    "explain": f"{PERSONA_V2} Answer helpfully and simply in at most 100 words. No 'Answer:' line.",
    "oasst2": f"{PERSONA_V2} Answer helpfully and simply in at most 100 words. No 'Answer:' line.",
    "chat": f"{PERSONA_V2} Reply like a warm, friendly companion in one to three short sentences. No 'Answer:' line.",
}
MATH_SYSTEM = ("Solve the problem in a few short steps. Write each step as one plain sentence with its calculation as an "
               "equation (for example: 48 - 6 = 42). Only the working: no jokes, no comparisons, no exclamations, no fun "
               "facts and no comments. Never use LaTeX: write × for times and / for divided by. The very last line must "
               "be 'Answer: <number>' with just the number, and nothing after it.")
MOOD_SYSTEM = "You classify the mood of a message to a children's assistant. Reply with exactly one word."
MOOD_USER = ("Message:\n{prompt}\n\nIs this message about something sad, worrying, painful or serious (illness, injury, "
             "death, loss, fear, bullying, a bad day, a safety problem)? Reply SERIOUS or OK.")

SIMILE = re.compile(  # build_finetune_set.SIMILE without the sentence-start anchor: any comparison anywhere
    r"\b(it'?s (?:kind of |sort of |a bit |a little |just )?like|it is like|(?:let'?s )?imagine|(?:let'?s )?pretend"
    r"|picture (?:this|a|an|it)|think of (?:it|this|that|them|him|her|my|your|a|an|the)\b|just like|like a|like an"
    r"|like the|as if)\b", re.I)
JOKE = re.compile(r"\b(haha|hehe|lol|fun fact|silly|giggl\w*|yay|woo+|wow)\b|!", re.I)
SENTENCE = re.compile(r"(?<=[.!?])\s+|\n+")
SYM = {"+": "+", "-": "-", "*": "×", "/": "÷"}
GOLD = {"+": lambda a, b: a + b, "-": lambda a, b: a - b, "*": lambda a, b: a * b, "/": lambda a, b: a // b}


def sentences(text):
    return [s.strip() for s in SENTENCE.split(text.strip()) if s.strip()]


def arith_reply(meta):
    op, a, b = meta.split("|")
    a, b = int(a), int(b)
    g = GOLD[op](a, b)
    return f"{a} {SYM[op]} {b} = {g}\n\nAnswer: {g}"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", default=str(SRC))
    p.add_argument("--out", required=True)
    p.add_argument("--limit", type=int, default=0, help="first N rows per category of each split (smoke test)")
    p.add_argument("--n", type=int, default=2, help="candidates per explain/chat/oasst2 request")
    p.add_argument("--gsm8k-n", type=int, default=3)
    p.add_argument("--max-aura-tokens", type=int, default=240)
    p.add_argument("--temperature", type=float, default=0.7)
    p.add_argument("--top-p", type=float, default=0.95)
    p.add_argument("--max-new-tokens", type=int, default=320)
    p.add_argument("--chunk", type=int, default=16000)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)
    aura_len = C.AuraLength()
    gsm_gold = {json.loads(line)["prompt"].strip(): json.loads(line)["gold"] for line in open(GSM8K_SRC)}

    splits = {}
    for split in ("train", "val"):
        rows = [json.loads(line) for line in open(Path(args.src) / f"{split}.jsonl")]
        if args.limit:
            per = Counter()
            rows = [r for r in rows if (per.update([r["category"]]) or per[r["category"]] <= args.limit)]
        for r in rows:
            r["split"] = split
        splits[split] = rows
    rows = splits["train"] + splits["val"]
    regen = [r for r in rows if r["category"] in SYSTEM_V2 or r["category"] == "gsm8k"]
    for r in regen:
        r["ask"] = r["category"] in C.ASK_CATEGORIES and rng.random() < C.ASK_RATE
        if r["category"] == "gsm8k":
            r["gold"] = gsm_gold.get(r["prompt"].strip())
    missing_gold = sum(r["category"] == "gsm8k" and r["gold"] is None for r in regen)
    seeds = C.per_request_seeds(args.seed + 11, len(regen))

    run_config = {
        "teacher": C.TEACHER, "teacher_license": C.TEACHER_LICENSE, "method": "sequence-level (text) distillation, "
        "regenerated replies for ft_v1 prompts", "src": str(Path(args.src).relative_to(C.ROOT)),
        "system_prompts": {**SYSTEM_V2, "gsm8k": MATH_SYSTEM}, "mood_judge": [MOOD_SYSTEM, MOOD_USER],
        "followup_question": {"rate": C.ASK_RATE, "yes": C.ASK_YES, "no": C.ASK_NO},
        "arith": "programmatic from ft_v1 meta, licence ours", "story": "copied from ft_v1",
        "n": args.n, "gsm8k_n": args.gsm8k_n, "temperature": args.temperature, "top_p": args.top_p,
        "max_new_tokens": args.max_new_tokens, "max_aura_tokens": args.max_aura_tokens, "seed": args.seed,
        "limit": args.limit, "prompt_licences": {"arith": "ours", "story": "ours", "explain": "Qwen output (Apache-2.0)",
                                                 "chat": "Qwen output (Apache-2.0)", "gsm8k": "MIT", "oasst2": "Apache-2.0"},
        "git_commit": subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=C.ROOT, capture_output=True,
                                     text=True).stdout.strip(),
        "started": time.strftime("%Y-%m-%dT%H:%M:%S"),
    }
    (out / "run_config.json").write_text(json.dumps(run_config, indent=1))

    from vllm import LLM, SamplingParams  # noqa: E402  (vLLM venv only)
    llm = LLM(model=C.TEACHER, dtype="bfloat16", max_model_len=2048, gpu_memory_utilization=0.85, seed=args.seed)
    t0 = time.time()

    # mood pass: which explain/chat/oasst2 prompts are serious
    talk = [r for r in regen if r["category"] in SYSTEM_V2]
    mood = llm.chat([[{"role": "system", "content": MOOD_SYSTEM},
                      {"role": "user", "content": MOOD_USER.format(prompt=r["prompt"])}] for r in talk],
                    SamplingParams(temperature=0.0, max_tokens=4), use_tqdm=False)
    for r, o in zip(talk, mood):
        r["serious"] = "SERIOUS" in o.outputs[0].text.upper()
    print(f"mood pass: {sum(r['serious'] for r in talk):,} of {len(talk):,} prompts serious, "
          f"{(time.time() - t0) / 60:.1f} min", flush=True)

    def check(r, reply, finish):
        c = r["category"]
        if finish != "stop":
            return "truncated"
        if C.IDENTITY.search(reply):
            return "identity"
        if "INST]" in reply:
            return "format"
        if C.LATEX.search(reply):
            return "latex"
        if C.CODE.search(reply):
            return "code"
        if c == "gsm8k":
            m = C.ANSWER.findall(reply)
            try:
                ok = r["gold"] is not None and bool(m) and float(m[-1].replace(",", "").rstrip(".")) == float(r["gold"])
            except ValueError:
                ok = False
            if not ok:
                return "wrong_answer"
            if not C.answer_is_last(reply):
                return "answer_not_last"
        elif "Answer:" in reply:
            return "answer_leak"
        if aura_len(r["prompt"], reply) > args.max_aura_tokens:
            return "too_long"
        sents = sentences(reply)
        if c == "gsm8k":
            return "playful_math" if SIMILE.search(reply) or JOKE.search(reply) else None
        if sents and SIMILE.search(sents[0]):
            return "simile_first"
        if len(SIMILE.findall(reply)) > 1:
            return "too_many_similes"
        if r.get("serious") and (SIMILE.search(reply) or JOKE.search(reply)):
            return "playful_serious"
        return None

    nd = C.NearDup(seed=args.seed)
    stats = defaultdict(Counter)
    new_reply = {}
    with open(out / "rejected.jsonl", "w") as fr:
        for i in range(0, len(regen), args.chunk):
            part = regen[i:i + args.chunk]
            convs = [[{"role": "system", "content": (MATH_SYSTEM if r["category"] == "gsm8k" else SYSTEM_V2[r["category"]]
                                                     + (C.ASK_YES if r["ask"] else C.ASK_NO))},
                      {"role": "user", "content": r["prompt"]}] for r in part]
            sps = [SamplingParams(temperature=args.temperature, top_p=args.top_p, max_tokens=args.max_new_tokens,
                                  n=args.gsm8k_n if r["category"] == "gsm8k" else args.n, seed=s)
                   for r, s in zip(part, seeds[i:i + args.chunk])]
            for r, o in zip(part, llm.chat(convs, sps, use_tqdm=False)):
                c = r["category"]
                stats[c]["requests"] += 1
                reasons, ok = [], []
                for oi in o.outputs:
                    reply = oi.text.strip()
                    why = check(r, reply, oi.finish_reason)
                    (reasons.append((why, reply)) if why else ok.append(reply))
                if c == "gsm8k" and ok:  # shortest passing reply, as generate_pilot.py
                    ok = [min(ok, key=len)]
                kept = None
                for reply in ok:
                    dup = nd.check_and_add(c, reply)
                    if dup:
                        reasons.append((dup, reply))
                        continue
                    kept = reply
                    break
                if kept is None:
                    why = Counter(w for w, _ in reasons).most_common(1)[0][0]
                    stats[c][why] += 1
                    fr.write(json.dumps({"category": c, "split": r["split"], "reason": why, "prompt": r["prompt"],
                                         "reply": reasons[0][1]}, ensure_ascii=False) + "\n")
                    continue
                for w, _ in reasons:
                    stats[c][f"candidate_{w}"] += 1
                new_reply[id(r)] = kept
                stats[c]["kept"] += 1
                stats[c]["kept_serious"] += bool(r.get("serious"))
                stats[c]["kept_question"] += C.ends_with_question(kept)
            fr.flush()
            done = min(i + args.chunk, len(regen))
            print(f"[{done:,}/{len(regen):,} requests, {(time.time() - t0) / 60:.1f} min] kept "
                  f"{sum(s['kept'] for s in stats.values()):,}", flush=True)

    keys = ("category", "source", "prompt_license", "teacher", "teacher_license", "aura_tokens", "meta", "prompt", "reply",
            "line")
    sizes = defaultdict(Counter)
    kept_rows = defaultdict(list)
    for split, rs in splits.items():
        with open(out / f"{split}.jsonl", "w") as f:
            for r in rs:
                c = r["category"]
                if c == "arith":
                    reply, teacher, lic = arith_reply(r["meta"]), "none (programmatic)", "ours"
                elif c == "story":
                    reply, teacher, lic = r["reply"], r["teacher"], r["teacher_license"]
                elif id(r) in new_reply:
                    reply, teacher, lic = new_reply[id(r)], C.TEACHER, C.TEACHER_LICENSE
                else:
                    sizes[c][f"{split}_dropped"] += 1
                    continue
                row = {**r, "teacher": teacher, "teacher_license": lic, "reply": reply,
                       "aura_tokens": aura_len(r["prompt"], reply), "line": f"[INST] {r['prompt']} [/INST] {reply}"}
                if c in SYSTEM_V2:
                    row["serious"] = r["serious"]
                    row["followup_asked"] = r["ask"]
                f.write(json.dumps({k: row[k] for k in keys + ("serious", "followup_asked") if k in row},
                                   ensure_ascii=False) + "\n")
                sizes[c][split] += 1
                sizes[c][f"{split}_tokens"] += row["aura_tokens"]
                kept_rows[c].append(row)

    def share(rs, fn):
        return sum(map(fn, rs)) / max(1, len(rs))

    L = ["# ft_v2 build report (fact-first)\n", f"Source `{run_config['src']}`, teacher {C.TEACHER} ({C.TEACHER_LICENSE}). "
         f"{(time.time() - t0) / 60:.1f} min. gsm8k rows without a gold answer: {missing_gold}.\n",
         "## Sizes (samples / AURA tokens, 16k-tokenizer count as ft_v1)\n",
         "| category | train | val | dropped (train/val) |", "|---|---|---|---|"]
    for c in sorted(sizes):
        s = sizes[c]
        L.append(f"| {c} | {s['train']:,} / {s['train_tokens'] / 1e6:.2f}M | {s['val']:,} / {s['val_tokens'] / 1e6:.2f}M | "
                 f"{s['train_dropped']:,} / {s['val_dropped']:,} |")
    L += ["\n## Regeneration (per request; a request is dropped when none of its candidates passes)\n",
          "| category | requests | kept | reasons for dropped requests | rejected candidates (all) |", "|---|---|---|---|---|"]
    for c, s in sorted(stats.items()):
        drop = ", ".join(f"{k} {v}" for k, v in s.most_common() if k not in ("requests", "kept", "kept_serious",
                                                                              "kept_question") and not k.startswith("candidate_"))
        cand = ", ".join(f"{k[10:]} {v}" for k, v in s.most_common() if k.startswith("candidate_"))
        L.append(f"| {c} | {s['requests']:,} | {s['kept']:,} | {drop or '-'} | {cand or '-'} |")
    L += ["\n## Style (kept replies, train + val)\n",
          "| category | comparison anywhere | comparison in 1st sentence | joke marker or '!' | ends in '?' | serious prompts |",
          "|---|---|---|---|---|---|"]
    for c in sorted(kept_rows):
        rs = kept_rows[c]
        L.append(f"| {c} | {share(rs, lambda r: bool(SIMILE.search(r['reply']))):.1%} | "
                 f"{share(rs, lambda r: bool(sentences(r['reply'])) and bool(SIMILE.search(sentences(r['reply'])[0]))):.1%} | "
                 f"{share(rs, lambda r: bool(JOKE.search(r['reply']))):.1%} | "
                 f"{share(rs, lambda r: C.ends_with_question(r['reply'])):.1%} | "
                 f"{share(rs, lambda r: bool(r.get('serious'))):.1%} |")
    (out / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))

    R = ["# ft_v2 review: random kept replies\n"]
    rr = random.Random(1)
    for c in sorted(kept_rows):
        R.append(f"\n## {c}\n")
        pool = kept_rows[c]
        picks = rr.sample(pool, min(8, len(pool)))
        if c in SYSTEM_V2:  # make sure serious prompts are represented
            ser = [r for r in pool if r.get("serious") and r not in picks]
            picks += rr.sample(ser, min(4, len(ser)))
        for r in picks:
            R.append(f"**You:** {r['prompt']}{'  *(serious)*' if r.get('serious') else ''}\n\n**Aura:** {r['reply']}\n")
    (out / "review.md").write_text("\n".join(R) + "\n")


if __name__ == "__main__":
    main()
