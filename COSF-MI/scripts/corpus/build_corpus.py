"""
Clean pretraining corpus v1 (commercial-safe: no GPT/closed-model text; see the licence table in CLAUDE.md).

Sources (downloaded parquet shards under data/corpus_v1/raw/, one folder each) and token shares:
  fineweb_edu    HuggingFaceFW/fineweb-edu sample/10BT        ODC-By (collection; web text keeps its authors' rights)   55%
  cosmopedia_v2  HuggingFaceTB/smollm-corpus cosmopedia-v2   ODC-By; text by Mixtral-8x7B-Instruct (Apache-2.0)         30%
  finemath4      HuggingFaceTB/finemath finemath-4plus        ODC-By                                                     10%
  aura_distill   data/distill_pilot/ft_v1/train.jsonl (TRAIN split only, never val): Qwen2.5-7B-Instruct
                 (Apache-2.0) replies + programmatic arithmetic, written as "You: … Aura: …" transcripts              1.5%
                 (all of it: tok24k asked for 5% and ran out at 1.5%)
  aura_arith     data/arith_corpus_v1/train.jsonl: plain-format arithmetic (build_arith_plain.py), same transcripts    3.5%

Subcommands:
  sample    a mixed plain-text sample (by the same shares) for tokenizer training -> data/corpus_v1/tok_sample.txt
  tokenize  documents -> uint16 token streams with </s> between documents, until each source's token budget is met:
            data/corpus_v1/<name>/{train.bin,val.bin,meta.json} (val = documents whose hash % 200 == 0, ~0.5%).
            Uses all CPU cores; the result loads with cosf_mi.data.memmap_dataset.load_corpus.

Usage (from COSF-MI/):
  .venv/bin/python scripts/corpus/build_corpus.py sample --mb 1500
  .venv/bin/python scripts/corpus/build_corpus.py tokenize --tokenizer models/tokenizer_clean24k.model --tokens 2.2e9 --name tok24k_v2   (tok24k = before aura_arith)
"""
import argparse
import hashlib
import json
import multiprocessing as mp
import random
import re
import time
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data/corpus_v1/raw"
SOURCES = {
    "fineweb_edu": {"share": 0.55, "glob": "fineweb_edu/**/*.parquet", "licence": "ODC-By 1.0 (collection; CommonCrawl web text)",
                    "repo": "HuggingFaceFW/fineweb-edu sample/10BT"},
    "cosmopedia_v2": {"share": 0.30, "glob": "cosmopedia_v2/**/*.parquet",
                      "licence": "ODC-By 1.0; text generated by Mixtral-8x7B-Instruct (Apache-2.0)",
                      "repo": "HuggingFaceTB/smollm-corpus cosmopedia-v2"},
    "finemath4": {"share": 0.10, "glob": "finemath4/**/*.parquet", "licence": "ODC-By 1.0 (collection; CommonCrawl web text)",
                  "repo": "HuggingFaceTB/finemath finemath-4plus"},
    "aura_distill": {"share": 0.015, "jsonl": "data/distill_pilot/ft_v1/train.jsonl",
                     "licence": "Apache-2.0 teacher outputs (Qwen2.5-7B-Instruct) + programmatic (ours)",
                     "repo": "local: data/distill_pilot/ft_v1 train split"},
    "aura_arith": {"share": 0.035, "jsonl": "data/arith_corpus_v1/train.jsonl",
                   "licence": "ours (programmatic arithmetic, no teacher)",
                   "repo": "local: scripts/distill/build_arith_plain.py --n 1830000 --seed 1 (plain format, 1-4 digits, + - × ÷)"},
}
_INST = re.compile(r"\[INST\]\s*(.*?)\s*\[/INST\]\s*(.*)", re.S)


def documents(name):
    """Yield the source's documents as plain text, in a fixed order (shards sorted by name under RAW)."""
    src = SOURCES[name]
    if "jsonl" in src:
        for line in open(ROOT / src["jsonl"], encoding="utf-8"):
            m = _INST.match(json.loads(line)["line"])
            if m:
                yield f"You: {m.group(1)}\nAura: {m.group(2)}"
        return
    for path in sorted(RAW.glob(src["glob"])):
        pf = pq.ParquetFile(path)
        for rg in range(pf.num_row_groups):
            for text in pf.read_row_group(rg, columns=["text"]).column("text").to_pylist():
                if text and len(text) > 200:
                    yield text.strip()


def is_val(doc):
    return int(hashlib.md5(doc[:500].encode("utf-8", "ignore")).hexdigest(), 16) % 200 == 0


def cmd_sample(args):
    out = ROOT / "data/corpus_v1/tok_sample.txt"
    budget = {n: s["share"] * args.mb * 1e6 for n, s in SOURCES.items()}
    with open(out, "w", encoding="utf-8") as f:
        for name in SOURCES:
            written = 0
            for doc in documents(name):
                if is_val(doc):
                    continue  # keep the val documents out of the tokenizer sample too
                for para in doc.split("\n"):
                    if para.strip():
                        f.write(para.strip() + "\n")
                        written += len(para) + 1
                if written >= budget[name]:
                    break
            print(f"sample {name}: {written / 1e6:.0f} MB", flush=True)
    print(f"wrote {out} ({out.stat().st_size / 1e9:.2f} GB)")


_sp = None


def _init(model_path):
    global _sp
    import sentencepiece as spm
    _sp = spm.SentencePieceProcessor(model_file=model_path)


def _encode(docs):
    eos = _sp.eos_id()
    return [np.array(ids + [eos], dtype=np.uint16) for ids in _sp.encode(docs)]


def cmd_tokenize(args):
    import sentencepiece as spm
    sp = spm.SentencePieceProcessor(model_file=str(ROOT / args.tokenizer))
    assert sp.vocab_size() < 65536, "uint16 storage needs a vocab under 65,536"
    global RAW
    RAW = ROOT / args.raw
    for kv in filter(None, args.shares.split(",")):  # e.g. "aura_distill:0,aura_arith:0.035"
        k, v = kv.split(":")
        SOURCES[k]["share"] = float(v)
    if args.arith_jsonl:
        SOURCES["aura_arith"]["jsonl"] = args.arith_jsonl
    out = ROOT / args.root / args.name
    out.mkdir(parents=True, exist_ok=True)
    counts = {n: {"train_tokens": 0, "val_tokens": 0, "docs": 0} for n in SOURCES}
    t0 = time.time()
    with open(out / "train.bin", "wb") as ftr, open(out / "val.bin", "wb") as fva, \
            mp.Pool(args.workers, initializer=_init, initargs=(str(ROOT / args.tokenizer),)) as pool:
        for name, src in SOURCES.items():
            budget = src["share"] * args.tokens
            if not budget:
                continue
            batch, batches = [], []

            def flush(batch):
                return pool.map_async(_encode, [batch[i:i + 256] for i in range(0, len(batch), 256)])

            done = False
            for doc in documents(name):
                batch.append(doc)
                if len(batch) >= 256 * args.workers * 4:
                    batches.append((batch, flush(batch)))
                    batch = []
                    while len(batches) > 2 or (batches and batches[0][1].ready()):
                        done = _write(batches.pop(0), counts[name], ftr, fva, budget)
                        if done:
                            break
                    if done:
                        break
            if not done:
                if batch:
                    batches.append((batch, flush(batch)))
                for b in batches:
                    if _write(b, counts[name], ftr, fva, budget):
                        break
            c = counts[name]
            print(f"{name}: {c['train_tokens'] / 1e6:.0f}M train + {c['val_tokens'] / 1e6:.1f}M val tokens, {c['docs']:,} docs "
                  f"(budget {budget / 1e6:.0f}M){'' if c['train_tokens'] >= budget else '  <- SOURCE RAN OUT'} "
                  f"[{time.time() - t0:.0f} s]", flush=True)
    shards = {n: sorted(str(q.relative_to(RAW)) for q in RAW.glob(s["glob"])) for n, s in SOURCES.items() if "glob" in s}
    meta = {"tokenizer": args.tokenizer, "raw": args.raw, "raw_shards": shards, "vocab_size": sp.vocab_size(), "eos_id": sp.eos_id(), "dtype": "uint16",
            "train_tokens": sum(c["train_tokens"] for c in counts.values()),
            "val_tokens": sum(c["val_tokens"] for c in counts.values()),
            "sources": {n: dict(counts[n], share=s["share"], licence=s["licence"], repo=s["repo"]) for n, s in SOURCES.items()},
            "val_rule": "md5(first 500 chars) % 200 == 0", "built": time.strftime("%Y-%m-%dT%H:%M:%S")}
    (out / "meta.json").write_text(json.dumps(meta, indent=1))
    print(json.dumps(meta, indent=1))


def _write(item, c, ftr, fva, budget):
    """Write one finished batch; True once the source's train budget is met. Documents are interleaved within a source
    by the batch order; the trainer shuffles windows, so cross-source order doesn't matter."""
    docs, res = item
    for chunk_docs, arrs in zip([docs[i:i + 256] for i in range(0, len(docs), 256)], res.get()):
        for doc, a in zip(chunk_docs, arrs):
            if is_val(doc):
                a.tofile(fva)
                c["val_tokens"] += len(a)
            else:
                a.tofile(ftr)
                c["train_tokens"] += len(a)
            c["docs"] += 1
        if c["train_tokens"] >= budget:
            return True
    return False


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sample")
    s.add_argument("--mb", type=float, default=1500)
    t = sub.add_parser("tokenize")
    t.add_argument("--tokenizer", required=True)
    t.add_argument("--tokens", type=float, default=2.2e9)
    t.add_argument("--name", required=True)
    t.add_argument("--workers", type=int, default=max(1, mp.cpu_count() - 4))
    t.add_argument("--raw", default="data/corpus_v1/raw", help="parquet shards, one folder per source")
    t.add_argument("--root", default="data/corpus_v1", help="output parent dir (the corpus goes to <root>/<name>)")
    t.add_argument("--shares", default="", help='override shares, e.g. "aura_distill:0" (0 = leave the source out)')
    t.add_argument("--arith-jsonl", default=None, help="aura_arith source file instead of data/arith_corpus_v1/train.jsonl")
    args = p.parse_args()
    random.seed(0)
    {"sample": cmd_sample, "tokenize": cmd_tokenize}[args.cmd](args)


if __name__ == "__main__":
    main()
